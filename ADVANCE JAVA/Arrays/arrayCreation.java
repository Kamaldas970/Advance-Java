package Arrays;

public class arrayCreation {

    public static void main(String[] args) {
        int marks[] = new int[30];
        marks[0] = 20;
        marks[1] = 30;
        marks[2] = 40;
        System.out.println("Total Marks Are :" + (marks[0] + marks[1] + marks[2]));
    }
}
